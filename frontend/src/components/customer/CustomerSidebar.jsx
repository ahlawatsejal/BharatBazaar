export default function CustomerSidebar({ onItemClick }) {
  const location = useLocation();
  const navigate = useNavigate();
  const { user, logout } = useAuth();

  const handleLogout = async () => {
    try {
      await logout();
      navigate('/');
    } catch {
      navigate('/');
    }
  };

  return (
    <aside
      className="w-full bg-white border border-[#EBE4DA] rounded-sm p-4 flex flex-col"
      style={{ fontFamily: 'var(--font-sans)' }}
    >
      {/* Customer summary banner */}
      <div className="pb-4 mb-4 border-b border-[#EBE4DA]">
        <div className="w-12 h-12 rounded-full bg-[#FAF4ED] text-[var(--burgundy)] flex items-center justify-center font-serif text-lg font-bold mb-2">
          {user?.first_name ? user.first_name[0].toUpperCase() : 'B'}
        </div>
        <p className="font-serif font-semibold text-sm text-[var(--brown-dark)] truncate">
          {user?.first_name ? `${user.first_name} ${user.last_name || ''}` : user?.email}
        </p>
        <p className="text-[11px] text-[var(--brown-light)] truncate">{user?.email}</p>
        <span className="inline-block mt-1.5 px-2 py-0.5 rounded text-[9.5px] font-bold uppercase tracking-wider bg-[#F7F2EB] text-[var(--burgundy)]">
          Verified Patron
        </span>
      </div>

      {/* Navigation items */}
      <nav className="space-y-1 flex-1">
        {NAV_ITEMS.map((item) => {
          const isActive = location.pathname === item.path || (item.path !== '/customer/dashboard' && location.pathname.startsWith(item.path));
          return (
            <Link
              key={item.path}
              to={item.path}
              onClick={onItemClick}
              className={`flex items-center gap-3 px-3 py-2.5 rounded-xs text-xs font-medium transition-colors ${
                isActive
                  ? 'bg-[var(--burgundy)] text-white'
                  : 'text-[var(--brown-mid)] hover:text-[var(--brown-dark)] hover:bg-[#FAF8F5]'
              }`}
            >
              <span className={isActive ? 'text-white' : 'text-[var(--brown-mid)]'}>
                {item.icon}
              </span>
              <span>{item.label}</span>
            </Link>
          );
        })}

        {/* 10. Logout Button */}
        <button
          type="button"
          onClick={handleLogout}
          className="w-full flex items-center gap-3 px-3 py-2.5 rounded-xs text-xs font-medium text-rose-700 hover:bg-rose-50 transition-colors mt-2 text-left cursor-pointer"
        >
          <svg className="w-4 h-4" fill="none" stroke="currentColor" viewBox="0 0 24 24">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth="1.8" d="M17 16l4-4m0 0l-4-4m4 4H7m6 4v1a3 3 0 01-3 3H6a3 3 0 01-3-3V7a3 3 0 013-3h4a3 3 0 013 3v1" />
          </svg>
          <span>Sign Out</span>
        </button>
      </nav>
    </aside>
  );
}
